import {test, expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('browser boots, edits, drags and downloads JSON/PNG/ZIP', async ({page}) => {
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', msg => { if(msg.type()==='error') errors.push(msg.text()); });
  await page.goto('/');
  console.log('loading');
  await expect(page.getByRole('button', {name:'Text',exact:true})).toBeVisible({timeout:120000});
  await expect(page.locator('#pui-status')).toBeHidden();
  await page.getByRole('button', {name:'Text',exact:true}).click();
  const content = page.locator('textarea:not([readonly])');
  await expect(content).toHaveValue('Hello {name}');
  await content.fill('Hello {customer}');
  await content.press('Tab');
  await expect(page.getByText('customer',{exact:true})).toBeVisible();
  const customer = page.locator('.pui-HBox').filter({has:page.getByText('customer',{exact:true})}).last().locator('input');
  await customer.fill('Ada');
  await customer.press('Tab');
  const canvas = page.locator('canvas').first();
  const bounds = await canvas.boundingBox();
  const scale = Math.min((bounds.width-24)/100, (bounds.height-24)/60);
  const ox = bounds.x+(bounds.width-100*scale)/2;
  const oy = bounds.y+(bounds.height-60*scale)/2;
  await page.mouse.move(ox+6*scale, oy+6*scale);
  await page.mouse.down();
  await page.mouse.move(ox+11*scale, oy+13*scale, {steps:4});
  await page.mouse.up();
  await page.getByRole('button', {name:'Save JSON',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.json',{exact:true})}).getByRole('link',{name:'Download',exact:true}).click();
  const download = await downloadPromise;
  console.log('JSON downloaded');
  const json = JSON.parse(await readFile(await download.path(),'utf8'));
  expect(json.canvas.dpi).toBe(300);
  expect(json.objects[0].content).toBe('Hello {customer}');
  expect(json.variables.customer).toBe('Ada');
  expect(json.objects[0].x_mm).toBeCloseTo(10,0);
  expect(json.objects[0].y_mm).toBeCloseTo(12,0);
  // Add the remaining renderer types, including a file-backed image.
  await page.getByRole('button', {name:'Rect',exact:true}).click();
  await expect(page.getByText('Corner R (mm)',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'QR',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveValue('https://example.com/{id}');
  await page.locator('textarea:not([readonly])').fill('https://example.com');
  await page.locator('textarea:not([readonly])').press('Tab');
  await page.getByRole('button', {name:'Code128',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveValue('{sku}');
  await page.locator('textarea:not([readonly])').fill('ABC123');
  await page.locator('textarea:not([readonly])').press('Tab');
  await expect(page.getByRole('button', {name:'● code128 · ABC123',exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Image',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveCount(0);
  console.log('choosing image');
  await page.getByRole('button', {name:'Choose image…',exact:true}).click();
  await page.locator('dialog input[type=file]').first().setInputFiles({
    name:'pixel.png',mimeType:'image/png',
    buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jC2kAAAAASUVORK5CYII=','base64')
  });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  console.log('image imported');
  await expect(page.locator('textarea[readonly]')).not.toHaveValue('');
  await page.getByRole('button', {name:'Export PNG',exact:true}).click();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const pngPromise=page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.png',{exact:true})}).getByRole('link',{name:'Download',exact:true}).click();
  const png=await readFile(await (await pngPromise).path());
  expect(png.subarray(1,4).toString()).toBe('PNG');
  console.log('PNG downloaded');
  await page.getByRole('button', {name:'Save ZIP',exact:true}).click();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const zipPromise=page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.zip',{exact:true})}).getByRole('link',{name:'Download',exact:true}).click();
  const zip=await readFile(await (await zipPromise).path());
  expect(zip.subarray(0,2).toString()).toBe('PK');
  console.log('ZIP downloaded');
  await page.screenshot({path:'test-results/labelate.png',fullPage:true});
  expect(errors).toEqual([]);
});
