import {decode} from '@msgpack/msgpack';
import {test, expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('browser boots, edits, drags and downloads LBL/PNG', async ({page}) => {
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', msg => { if(msg.type()==='error') errors.push(msg.text()); });
  await page.goto('/');
  console.log('loading');
  await expect(page.getByRole('button', {name:'Text',exact:true})).toBeVisible({timeout:120000});
  await expect(page.locator('#pui-status')).toBeHidden();
  await page.getByRole('button', {name:'Text',exact:true}).click();
  const content = page.locator('textarea:not([readonly])');
  await expect(content).toHaveValue('Hello {name}');
  await expect(page.getByText('Noto Sans CJK TC',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Choose font…'})).toHaveCount(0);
  await content.fill('標籤 {customer}\n第二行');
  await content.press('Tab');
  await expect(page.getByRole('tabpanel',{name:'Label'}).getByText('customer',{exact:true})).toBeVisible();
  const customer = page.locator('.pui-HBox').filter({has:page.getByText('customer',{exact:true})}).last().locator('input');
  await customer.fill('Ada');
  await customer.press('Tab');
  console.log('checking print controls');
  await expect(page.getByRole('button',{name:'Print Single Label',exact:true})).toBeDisabled();
  await expect(page.locator('.pui-HBox').filter({has:page.getByText('Copies',{exact:true})}).last().locator('input:visible')).toHaveValue('1');
  console.log('switching Data');
  await page.getByRole('tab',{name:'Data',exact:true}).click();
  await expect(page.getByRole('button',{name:'Print All',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Print Single Label',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Add row',exact:true}).click();
  const dataPanel=page.getByRole('tabpanel',{name:'Data'});
  await dataPanel.getByRole('cell',{name:'Ada',exact:true}).click();
  await dataPanel.getByRole('textbox',{name:'Edit cell'}).fill('Bob');
  // Switching tabs commits the still-focused data cell.
  await page.getByRole('tab',{name:'Label',exact:true}).click();
  await expect(page.getByRole('tabpanel',{name:'Label'})).toBeVisible();
  console.log('Data edited');
  const canvas = page.locator('canvas').first();
  const bounds = await canvas.boundingBox();
  const scale = Math.min((bounds.width-24)/100, (bounds.height-24)/60);
  const ox = bounds.x+(bounds.width-100*scale)/2;
  const oy = bounds.y+(bounds.height-60*scale)/2;
  await page.mouse.move(ox+6*scale, oy+6*scale);
  await page.mouse.down();
  await page.mouse.move(ox+11*scale, oy+13*scale, {steps:4});
  await page.mouse.up();
  await page.getByRole('button', {name:'Save .lbl',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.lbl',{exact:true})}).getByRole('link',{name:'Download',exact:true}).click();
  const download = await downloadPromise;
  console.log('LBL downloaded');
  await page.getByRole('button',{name:'Dismiss label.lbl',exact:true}).click();
  const json = decode(await readFile(await download.path()));
  expect(json.canvas.dpi).toBe(300);
  expect(json.data_rows).toEqual([{customer:'Bob'}]);
  expect(json.objects[0].content).toBe('標籤 {customer}\n第二行');
  expect(json.variables.customer).toBe('Ada');
  expect(json.objects[0].x_mm).toBeCloseTo(10,0);
  expect(json.objects[0].y_mm).toBeCloseTo(12,0);
  // Add the remaining renderer types, including a embedded image.
  await page.getByRole('button', {name:'Rect',exact:true}).click();
  await expect(page.getByText('Corner R (mm)',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'QR',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveValue('https://example.com/{id}');
  await page.locator('textarea:not([readonly])').fill('https://example.com');
  await page.locator('textarea:not([readonly])').press('Tab');
  await page.getByRole('button', {name:'Code128',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveValue('{sku}');
  await page.locator('textarea:not([readonly])').fill('ABC123');
  await page.locator('textarea:not([readonly])').press('Tab');
  await expect(page.getByRole('button', {name:'● code128 · ABC123',exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Image',exact:true}).click();
  await expect(page.locator('textarea:not([readonly])')).toHaveCount(0);
  console.log('choosing image');
  await page.getByRole('button', {name:'Choose image…',exact:true}).click();
  await page.locator('dialog input[type=file]').first().setInputFiles({
    name:'pixel',mimeType:'image/png',
    buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAEElEQVR4nGP8zwACTGCSAQANHQEDgslx/wAAAABJRU5ErkJggg==','base64')
  });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  console.log('image imported');
  await expect(page.getByText('pixel',{exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Export PNG',exact:true}).click();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const pngPromise=page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.png',{exact:true})}).getByRole('link',{name:'Download',exact:true}).click();
  const png=await readFile(await (await pngPromise).path());
  expect(png.subarray(1,4).toString()).toBe('PNG');
  console.log('PNG downloaded');
  await page.getByRole('button', {name:'Save .lbl',exact:true}).click();
  await page.getByRole('dialog').getByRole('button', {name:'Download',exact:true}).click();
  const lblPromise=page.waitForEvent('download');
  await page.locator('.pui-download-card').filter({has:page.getByText('label.lbl',{exact:true})}).last().getByRole('link',{name:'Download',exact:true}).click();
  const lbl=await readFile(await (await lblPromise).path());
  const saved=decode(lbl);
  const embedded=saved.objects.find(obj=>obj.type==='image');
  expect(embedded.data).toBeInstanceOf(Uint8Array);
  expect(Buffer.from(embedded.data).subarray(1,4).toString()).toBe('PNG');
  await page.getByRole('button',{name:'Open .lbl',exact:true}).click();
  await page.locator('dialog input[type=file]').first().setInputFiles({
    name:'roundtrip.lbl',mimeType:'application/octet-stream',buffer:lbl
  });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:/image · pixel/})).toBeVisible();
  await page.screenshot({path:'test-results/labelate.png',fullPage:true});
  expect(errors).toEqual([]);
});
